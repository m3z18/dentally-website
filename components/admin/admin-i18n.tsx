const toEnglish = new Map(pairs.map(([ar, en]) => [ar, en]));
const toArabic = new Map(pairs.map(([ar, en]) => [en, ar]));

export function translateAdminText(value: string, locale: Locale) {
  const trimmed = value.trim();
  if (!trimmed) return value;
  if (trimmed === "صور المنشأة فقط. صور المرضى وBefore/After غير مفعلة.") {
    return value.replace(trimmed, locale === "ar"
      ? "صور المنشأة فقط. صور المرضى وصور قبل/بعد غير مفعلة."
      : "Facility images only. Patient and before/after images are disabled.");
  }
  const translated = (locale === "en" ? toEnglish : toArabic).get(trimmed);
  if (translated) return value.replace(trimmed, translated);

  if (locale === "en") {
    const appointments = trimmed.match(/^(\d+) موعد$/);
    if (appointments) return value.replace(trimmed, `${appointments[1]} appointments`);
    const doctors = trimmed.match(/^(\d+) طبيب$/);
    if (doctors) return value.replace(trimmed, `${doctors[1]} doctors`);
    const dateLabel = trimmed.match(/^التاريخ: (.+)$/);
    if (dateLabel) return value.replace(trimmed, `Date: ${dateLabel[1]}`);
  }

  return value;
}

type AdminI18nValue = {
  locale: Locale;
  direction: "rtl" | "ltr";
  t: (arabic: string, english: string) => string;
  translate: (value: string) => string;
};

const AdminI18nContext = createContext<AdminI18nValue>({
  locale: "ar",
  direction: "rtl",
  t: (arabic) => arabic,
  translate: (value) => value,
});

export function AdminI18nProvider({ initialLocale, children }: { initialLocale: Locale; children: ReactNode }) {
  const locale = initialLocale;
  const value: AdminI18nValue = {
    locale,
    direction: locale === "ar" ? "rtl" : "ltr",
    t: (arabic, english) => (locale === "ar" ? arabic : english),
    translate: (text) => translateAdminText(text, locale),
  };

  return <AdminI18nContext.Provider value={value}>{children}</AdminI18nContext.Provider>;
}

export function useAdminI18n() {
  return useContext(AdminI18nContext);
}

export function AdminLanguageSwitcher({ compact = false }: { compact?: boolean }) {
  const { locale, t } = useAdminI18n();
  const router = useRouter();

  function changeLanguage(next: Locale) {
    if (next === locale) return;
    document.cookie = `${localeCookieName}=${next}; Path=/; Max-Age=31536000; SameSite=Lax`;
    router.refresh();
  }

  return (
    <div className={`mx-auto inline-flex w-fit max-w-full items-center rounded-full border border-line bg-surface-muted/60 p-1 ${compact ? "text-[11px]" : "text-xs"}`} aria-label={t("اختيار اللغة", "Language selection")}>
      <button type="button" onClick={() => changeLanguage("ar")} aria-pressed={locale === "ar"} className={`min-h-8 shrink-0 rounded-full px-2.5 font-bold transition-colors focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brand ${locale === "ar" ? "bg-brand text-white" : "bg-transparent text-muted hover:bg-surface hover:text-foreground"}`} lang="ar" dir="rtl">
        العربية
      </button>
      <button type="button" onClick={() => changeLanguage("en")} aria-pressed={locale === "en"} className={`min-h-8 shrink-0 rounded-full px-2.5 font-bold transition-colors focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brand ${locale === "en" ? "bg-brand text-white" : "bg-transparent text-muted hover:bg-surface hover:text-foreground"}`} lang="en" dir="ltr">
        English
      </button>
    </div>
  );
}
